USE DATABASE ADVWORKS_DEV;
USE SCHEMA SCHEMATIZE;

CREATE OR REPLACE SEQUENCE CUSTOMER_SK_SEQ
START = 1
INCREMENT = 1;

CREATE OR REPLACE TABLE DIM_CUSTOMER
(
    CUSTOMER_SK              INTEGER,
    CUSTOMER_KEY             INTEGER,
    CUSTOMER_ALTERNATE_KEY   VARCHAR(20),

    FIRST_NAME               VARCHAR(100),
    MIDDLE_NAME              VARCHAR(100),
    LAST_NAME                VARCHAR(100),

    FULL_NAME                VARCHAR(300),

    BIRTH_DATE               DATE,
    GENDER                   VARCHAR(1),
    MARITAL_STATUS           VARCHAR(1),

    EMAIL_ADDRESS            VARCHAR(255),
    YEARLY_INCOME            NUMBER(18,2),

    TOTAL_CHILDREN           INTEGER,
    HOUSE_OWNER_FLAG         BOOLEAN,
    NUMBER_CARS_OWNED        INTEGER,

    COMMUTE_DISTANCE         VARCHAR(50),

    SOURCE_FILE              VARCHAR(500),
    CREATED_TIMESTAMP        TIMESTAMP_NTZ,
    UPDATED_TIMESTAMP        TIMESTAMP_NTZ
);

--load it

INSERT INTO SCHEMATIZE.DIM_CUSTOMER
SELECT
    CUSTOMER_SK_SEQ.NEXTVAL,

    CUSTOMER_KEY,
    CUSTOMER_ALTERNATE_KEY,

    FIRST_NAME,
    MIDDLE_NAME,
    LAST_NAME,

    CONCAT_WS(
        ' ',
        FIRST_NAME,
        MIDDLE_NAME,
        LAST_NAME
    ) AS FULL_NAME,

    BIRTH_DATE,
    GENDER,
    MARITAL_STATUS,

    EMAIL_ADDRESS,
    YEARLY_INCOME,

    TOTAL_CHILDREN,
    HOUSE_OWNER_FLAG,
    NUMBER_CARS_OWNED,

    COMMUTE_DISTANCE,

    SOURCE_FILE,
    CURRENT_TIMESTAMP(),
    CURRENT_TIMESTAMP()

FROM NORMALIZE.DIMCUSTOMER_NORMALIZED;

-- validate
SELECT COUNT(*)
FROM SCHEMATIZE.DIM_CUSTOMER; -- 18484

SELECT
    CUSTOMER_SK,
    CUSTOMER_KEY,
    FULL_NAME,
    EMAIL_ADDRESS
FROM SCHEMATIZE.DIM_CUSTOMER
ORDER BY CUSTOMER_SK
LIMIT 10;
