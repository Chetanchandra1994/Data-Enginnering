-- check whether every product referenced by the fact exists in the dimension:
SELECT
    COUNT(DISTINCT N.PRODUCT_KEY) AS NORMALIZE_PRODUCTS,
    COUNT(DISTINCT P.PRODUCT_KEY) AS DIM_PRODUCTS
FROM ADVWORKS_DEV.NORMALIZE.FACTINTERNETSALES_NORMALIZED N
LEFT JOIN ADVWORKS_DEV.SCHEMATIZE.DIM_PRODUCT P
    ON N.PRODUCT_KEY = P.PRODUCT_KEY;
