WITH watermark AS (

    SELECT
        COALESCE(
            MAX(LOAD_TIMESTAMP),
            TO_TIMESTAMP_NTZ('1900-01-01')
        ) AS MAX_LOAD_TIMESTAMP

    FROM {{ this }}

),

ranked AS (

    SELECT
        CUSTOMER_KEY,
        GEOGRAPHY_KEY,
        CUSTOMER_ALTERNATE_KEY,
        TITLE,
        FIRST_NAME,
        MIDDLE_NAME,
        LAST_NAME,
        NAME_STYLE,
        BIRTH_DATE,
        MARITAL_STATUS,
        SUFFIX,
        GENDER,
        EMAIL_ADDRESS,
        YEARLY_INCOME,
        TOTAL_CHILDREN,
        NUMBER_CHILDREN_AT_HOME,
        ENGLISH_EDUCATION,
        SPANISH_EDUCATION,
        FRENCH_EDUCATION,
        ENGLISH_OCCUPATION,
        SPANISH_OCCUPATION,
        FRENCH_OCCUPATION,
        HOUSE_OWNER_FLAG,
        NUMBER_CARS_OWNED,
        ADDRESS_LINE_1,
        ADDRESS_LINE_2,
        PHONE,
        DATE_FIRST_PURCHASE,
        COMMUTE_DISTANCE,
        SOURCE_FILE,
        LOAD_TIMESTAMP,

        ROW_NUMBER() OVER (
            PARTITION BY CUSTOMER_KEY
            ORDER BY LOAD_TIMESTAMP DESC
        ) AS RN

    FROM {{ ref('dim_customer_prepare') }}

    WHERE LOAD_TIMESTAMP > (
        SELECT MAX_LOAD_TIMESTAMP
        FROM watermark
    )
)

