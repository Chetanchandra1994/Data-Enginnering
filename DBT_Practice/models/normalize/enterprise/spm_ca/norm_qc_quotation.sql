--,QQ.SPECFC_DATE::DATE AS SPECFC_DATE
,NULLIF(TRIM(QQ.SPECFC_DESC::string), '') AS SPECFC_DESC
,NULLIF(TRIM(QQ.INPUT_BY_INIT_CODE::string), '') AS INPUT_BY_INIT_CODE
,QQ.PO_DATE::DATE AS PO_DATE
,UPPER(NULLIF(TRIM(QQ.COUNTRY::string),'')) AS COUNTRY
