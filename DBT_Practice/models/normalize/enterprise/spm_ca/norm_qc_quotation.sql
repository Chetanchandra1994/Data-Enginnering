,UPPER(NULLIF(TRIM(QQ.ST::string),'')) AS ST
,TO_BOOLEAN(QQ.APPLY_FEE::string) AS APPLY_FEE
-- always 0
--,QQ.PUBLIC::INTEGER AS PUBLIC
-- always 0
--,QQ.OPENING_FEE::INTEGER AS OPENING_FEE
,NULLIF(TRIM(QQ.CLASS_CATEG::string), '') AS CLASS_CATEG
,NULLIF(TRIM(QQ.CLASS_CODE::string), '') AS CLASS_CODE
,TO_BOOLEAN(QQ.FOLLOW_UP::string) AS FOLLOW_UP
,TIMESTAMPADD(second , QQ.LAST_UPDATE_TIME::INTEGER ,QQ.LAST_UPDATE_DATE::DATE ) AS LAST_UPDATE_DATETIME 
,TO_BOOLEAN(QQ.HOT::string) AS HOT
,QQ.LOST_DATE::DATE AS LOST_DATE
,QQ.MARK_QTY::INTEGER AS MARK_QTY
,QQ.STANDING_ID::INTEGER AS STANDING_ID
