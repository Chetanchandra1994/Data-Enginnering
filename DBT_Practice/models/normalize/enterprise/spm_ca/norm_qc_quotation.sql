,TO_TIMESTAMP_NTZ(QQ.LAST_LOADED_ESTIMATION_FILE_DATETIME) AS LAST_LOADED_ESTIMATION_FILE_DATETIME
,NULLIF(TRIM(QQ.CONTRC_BUYER_CONTACT_UUID::string),'') AS CONTRC_BUYER_CONTACT_UUID
,NULLIF(TRIM(QQ.CONTRC_PROJ_MANAGER_CONTACT_UUID::string),'') AS CONTRC_PROJ_MANAGER_CONTACT_UUID
,LOWER(NULLIF(TRIM(QQ.VES_ENTRY_COMPLETED_USER_CODE::string),'')) AS VES_ENTRY_COMPLETED_USER_CODE
,TO_BOOLEAN(QQ.ESTIMATION_INCLUDE_DESIGN::string) AS ESTIMATION_INCLUDE_DESIGN
,TO_BOOLEAN(QQ.LEAD::string) AS LEAD
,UPPER(NULLIF(TRIM(QQ.LEAD_PROSPECTOR_INIT_CODE::string::string),'')) AS LEAD_PROSPECTOR_INIT_CODE
,TO_BOOLEAN(QQ.LEED_CERTIFIED::string) AS LEED_CERTIFIED
,TO_BOOLEAN(QQ.EXTRA_CREDIT::string) AS EXTRA_CREDIT
,QQ.SIGNATORY_APPROVAL_STATUS::INTEGER AS SIGNATORY_APPROVAL_STATUS
-- always 0
--,QQ.SIGNATORY_APPROVED_AMOUNT::DOUBLE AS SIGNATORY_APPROVED_AMOUNT
,NULLIF(TRIM(QQ.BID_CUSTOMER_UUID::string),'') AS BID_CUSTOMER_UUID
,NULLIF(TRIM(QQ.CONTRACT_CUSTOMER_UUID::string),'') AS CONTRACT_CUSTOMER_UUID
,TO_BOOLEAN(QQ.SHOW_ADDRESSES_ON_FPS::string) AS SHOW_ADDRESSES_ON_FPS
,NULLIF(TRIM(QQ.QUOTATION_UUID::string),'') AS QUOTATION_UUID
,QQ.DECK_CALC_SOFT::INTEGER AS DECK_CALC_SOFT
,TO_BOOLEAN(QQ.DOMESTIC_STEEL_ONLY::string) AS DOMESTIC_STEEL_ONLY
,TO_BOOLEAN(QQ.MILL_TEST_REQUIRED::string) AS MILL_TEST_REQUIRED
,NULLIF(TRIM(QQ.LAST_LOADED_ESTIMATION_FILE_LOAD_BY::string), '') AS LAST_LOADED_ESTIMATION_FILE_LOAD_BY
,TO_BOOLEAN(QQ.PROJECT_TYPE::string) AS PROJECT_TYPE
,QQ.QUOTATION_TYPE_UUID::string AS QUOTATION_TYPE_UUID
,TO_BOOLEAN(QQ.LAST_LOADED_ESTIMATION_BUDGET_FORMAT::string) AS LAST_LOADED_ESTIMATION_BUDGET_FORMAT
-- always FALSE
--,TO_BOOLEAN(QQ.DRAFTING_CONTRACT::string) AS DRAFTING_CONTRACT
,NULLIF(TRIM(QQ.QUOTATION_MAIN_PRODUCT::string),'') AS QUOTATION_MAIN_PRODUCT
,QQ.QUOTATION_SENT_DATE::DATE AS QUOTATION_SENT_DATE
,TO_BOOLEAN(QQ.ERECTOR_PRIVILEGE_INCLUDED::string) AS ERECTOR_PRIVILEGE_INCLUDED
,INITCAP(NULLIF(TRIM(QQ.DELIVERY_OFFICE_CODE::string), '')) AS DELIVERY_OFFICE_CODE
,INITCAP(NULLIF(TRIM(QQ.DELIVERY_BRANCH_OFFICE_CODE::string), '')) AS DELIVERY_BRANCH_OFFICE_CODE
,TO_TIMESTAMP_NTZ(QQ.ESTIMATION_TARGET_DATETIME::string) AS ESTIMATION_TARGET_DATETIME
,TO_BOOLEAN(QQ.IS_NATIONAL_ACCOUNT::string) AS IS_NATIONAL_ACCOUNT
,QQ.OPPORTUNITY_RATING::INTEGER AS OPPORTUNITY_RATING
,QQ.OPPORTUNITY_STATUS::INTEGER AS OPPORTUNITY_STATUS
,QQ.OPPORTUNITY_STAGE::INTEGER AS OPPORTUNITY_STAGE
,QQ.COMPLX_CODE::INTEGER AS COMPLX_CODE
,QQ.LOST_PRICE_DELTA::INTEGER AS LOST_PRICE_DELTA
,QQ.CONFIDENCE_RATING::INTEGER AS CONFIDENCE_RATING
,QQ.LOST_TO_COMPT_NO::INTEGER AS LOST_TO_COMPT_NO
,QQ.OPPORTUNITY_DELIEVERY_DATE_SPAN::INTEGER AS OPPORTUNITY_DELIVERY_DATE_SPAN
,QQ.OPPORTUNITY_DELIEVERY_DATE_SPAN_MIN::DATE AS OPPORTUNITY_DELIVERY_DATE_SPAN_MIN
,QQ.OPPORTUNITY_DELIEVERY_DATE_SPAN_MAX::DATE AS OPPORTUNITY_DELIVERY_DATE_SPAN_MAX

-- for adding RDM_PROJECT_STEP from RDM
,RDM.STANDARD_APPLICATION_VALUE AS RDM_PROJECT_STEP

,CASE WHEN NULLIF(TRIM(QQ.OFFICE_CODE ::STRING),'') IS NULL 
  THEN NULL 
  ELSE IFNULL(RDM1.STANDARD_APPLICATION_VALUE,'Not Found') 
  END                                                                 AS RDM_SALES_OFFICE_DEPARTMENT_CODE
,CASE WHEN NULLIF(TRIM(QQ.BRANCH_OFFICE_CODE::STRING),'') IS NULL 
  THEN NULL 
  ELSE IFNULL(RDM_SBOD.STANDARD_APPLICATION_VALUE,'Not Found') 
  END                                                                 AS RDM_SALES_BRANCH_OFFICE_DEPARTMENT_CODE
,CASE WHEN QQ.ACTIVE IS NULL 
  THEN NULL 
  ELSE IFNULL(RDM2.STANDARD_APPLICATION_VALUE,'Not Found') 
  END                                                                 AS RDM_ACTIVE_STATUS_CODE
,CASE WHEN NULLIF(TRIM(QQ.COUNTRY::STRING),'') IS NULL 
  THEN NULL 
  ELSE IFNULL(RDM_C.STANDARD_APPLICATION_VALUE,'Not Found') 
  END                                                                 AS RDM_COUNTRY_CODE

,TO_TIMESTAMP_NTZ(QQ.CREATED_DATE::string) AS CREATED_DATE
,NULLIF(TRIM(QQ.CREATED_BY::string), '') AS CREATED_BY
,TO_TIMESTAMP_NTZ(QQ.MODIFIED_DATE::string) AS MODIFIED_DATE
,NULLIF(TRIM(QQ.MODIFIED_BY::string), '') AS MODIFIED_BY
,CASE WHEN NULLIF(TRIM(QQ.OFFICE_CODE ::STRING),'') 
IS NULL THEN NULL ELSE IFNULL(RDM1.STANDARD_APPLICATION_VALUE_NAME_FR,'Not Found')
END                                      AS RDM_SALES_OFFICE_DEPARTMENT_NAME_FR
,CASE WHEN NULLIF(TRIM(QQ.OFFICE_CODE ::STRING),'') 
IS NULL THEN NULL ELSE IFNULL(RDM1.STANDARD_APPLICATION_VALUE_NAME_EN ,'Not Found') 
END                                      AS RDM_SALES_OFFICE_DEPARTMENT_NAME_EN
,CASE WHEN NULLIF(TRIM(QQ.BRANCH_OFFICE_CODE::STRING),'') 
IS NULL THEN NULL ELSE IFNULL(RDM_SBOD.STANDARD_APPLICATION_VALUE_NAME_FR,'Not Found') 
END                                      AS RDM_SALES_BRANCH_OFFICE_DEPARTMENT_NAME_FR
,CASE WHEN NULLIF(TRIM(QQ.BRANCH_OFFICE_CODE::STRING),'') 
IS NULL THEN NULL ELSE IFNULL(RDM_SBOD.STANDARD_APPLICATION_VALUE_NAME_EN ,'Not Found') 
END                                      AS RDM_SALES_BRANCH_OFFICE_DEPARTMENT_NAME_EN
,CASE WHEN NULLIF(TRIM(QQ.COUNTRY::STRING),'') 
IS NULL THEN NULL ELSE IFNULL(RDM_C.STANDARD_APPLICATION_VALUE_NAME_FR,'Not Found') 
END                                      AS RDM_COUNTRY_NAME_FR
,CASE WHEN NULLIF(TRIM(QQ.COUNTRY::STRING),'') 
IS NULL THEN NULL ELSE IFNULL(RDM_C.STANDARD_APPLICATION_VALUE_NAME_EN ,'Not Found') 
END                                      AS RDM_COUNTRY_NAME_EN
,CASE WHEN QQ.ACTIVE IS NULL 
THEN NULL ELSE IFNULL(RDM2.STANDARD_APPLICATION_VALUE_NAME_FR,'Not Found') 
END                                      AS RDM_ACTIVE_STATUS_NAME_FR
,CASE WHEN QQ.ACTIVE IS NULL 
THEN NULL ELSE IFNULL(RDM2.STANDARD_APPLICATION_VALUE_NAME_EN ,'Not Found') 
END                                      AS RDM_ACTIVE_STATUS_NAME_EN

