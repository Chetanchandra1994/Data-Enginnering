LEFT JOIN {{ref('gov_referencedata_rdm')}} RDM
ON UPPER(QQ.PROJCT_STEP) = UPPER(RDM.BUSINESS_APPLICATION_VALUE) 
AND UPPER(RDM.BUSINESS_APPLICATION_DOMAIN_CODE) = 'PROJECTSTEP' 
AND UPPER(RDM.STANDARD_DOMAIN_APPLICATION_CODE) = 'PROJECTSTEP'
AND UPPER(RDM.BUSINESS_APPLICATION_CODE) = 'SPM'
LEFT JOIN {{ref('gov_referencedata_rdm')}} RDM1
ON UPPER(TRIM(QQ.OFFICE_CODE)) = UPPER(TRIM(RDM1.BUSINESS_APPLICATION_VALUE))
AND UPPER(RDM1.BUSINESS_APPLICATION_DOMAIN_CODE) = 'SALESOFFICEDEPARTMENT'
AND UPPER(RDM1.STANDARD_DOMAIN_APPLICATION_CODE) = 'SALESOFFICEDEPARTMENT' 
AND UPPER(RDM1.BUSINESS_APPLICATION_CODE) = 'SPM'
LEFT JOIN {{ref('gov_referencedata_rdm')}} RDM_SBOD 
ON UPPER(NULLIF(TRIM(QQ.BRANCH_OFFICE_CODE::STRING),'')) = UPPER(RDM_SBOD.BUSINESS_APPLICATION_VALUE)
AND UPPER(RDM_SBOD.BUSINESS_APPLICATION_DOMAIN_CODE) = 'SALESBRANCHOFFICEDEPARTMENT'
AND UPPER(RDM_SBOD.STANDARD_DOMAIN_APPLICATION_CODE) = 'SALESBRANCHOFFICEDEPARTMENT' 
AND UPPER(RDM_SBOD.BUSINESS_APPLICATION_CODE) = 'SPM'
LEFT JOIN {{ref('gov_referencedata_rdm')}} RDM2
ON CAST(QQ.ACTIVE AS INT)= CAST(RDM2.BUSINESS_APPLICATION_VALUE AS INT) 
AND UPPER(RDM2.BUSINESS_APPLICATION_DOMAIN_CODE) = 'ACTIVESTATUS'
AND UPPER(RDM2.STANDARD_DOMAIN_APPLICATION_CODE) = 'ACTIVESTATUS' 
AND UPPER(RDM2.BUSINESS_APPLICATION_CODE) = 'SPM'
LEFT JOIN {{ref('gov_referencedata_rdm')}} RDM_C 
ON UPPER(NULLIF(TRIM(QQ.COUNTRY::STRING),'')) = UPPER(RDM_C.BUSINESS_APPLICATION_VALUE)
AND UPPER(RDM_C.BUSINESS_APPLICATION_DOMAIN_CODE) = 'COUNTRY'
AND UPPER(RDM_C.STANDARD_DOMAIN_APPLICATION_CODE) = 'COUNTRY' 
AND UPPER(RDM_C.BUSINESS_APPLICATION_CODE) = 'SPM'