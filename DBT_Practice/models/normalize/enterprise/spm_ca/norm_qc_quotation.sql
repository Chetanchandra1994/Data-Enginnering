--,QQ.MARKUP_WEIGHT::INTEGER AS MARKUP_WEIGHT
-- always null
--,QQ.MARKUP_PRICE_PERCENT::INTEGER AS MARKUP_PRICE_PERCENT
-- always null
--,QQ.MARKUP_PRICE_DOLLAR::string AS MARKUP_PRICE_DOLLAR
