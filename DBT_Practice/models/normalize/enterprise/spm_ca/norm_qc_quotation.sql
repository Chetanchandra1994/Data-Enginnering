,NULLIF(TRIM(QQ.ADRESSE_LIV_1::string), '') AS ADRESSE_LIV_1
,NULLIF(TRIM(QQ.ADRESSE_LIV_2::string), '') AS ADRESSE_LIV_2
,NULLIF(TRIM(QQ.ADRESSE_LIV_3::string), '') AS ADRESSE_LIV_3
,NULLIF(QQ.FOB_CODE::string,'') AS FOB_CODE
,NULLIF(TRIM(QQ.MEMO::string), '') AS MEMO
,NULLIF(TRIM(QQ.DUMMY::string,'"|'),'') AS DUMMY
,NULLIF(QQ.USER_CODE::string,'') AS USER_CODE
,INITCAP(QQ.DSG_ENTITY_CODE::string) AS DSG_ENTITY_CODE
-- always null
--,QQ.MARKUP_WEIGHT_PERCENT::INTEGER AS MARKUP_WEIGHT_PERCENT
