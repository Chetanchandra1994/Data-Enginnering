-- always NULL
--,QQ.DESIGN_DATE::DATE AS DESIGN_DATE
-- always NULL
--,NULLIF(TRIM(QQ.DESIGN_DESC::string), '') AS DESIGN_DESC
,TO_BOOLEAN(QQ.ADDEND::string) AS ADDEND
-- always NULL
