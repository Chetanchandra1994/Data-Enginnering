{{
  config(
    materialized = "view",
    alias = "business_unit",
    schema='spm_gdm',
    meta = {
        'table_key': 'BUSINESS_UNIT_ID',
        'tests': {
            'null_values':{
                'columns':[
                    'RDM_ACTIVE_STATUS_CODE'
                ]
            }
        }
    }
  )
