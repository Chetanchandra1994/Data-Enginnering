SELECT
    S.SUPPLIER_NUMBER,
    S.SUPPLIER_NAME,
    S.SUPPLIER_TYPE_CODE,
    CASE WHEN SPI.INVOICE_DATE BETWEEN DD1.FULL_DATE AND DD2.FULL_DATE THEN DD1.FULL_DATE ELSE NULL END  AS AUDIT_EFFECTIVE_START_DATE,
    CASE WHEN SPI.INVOICE_DATE BETWEEN DD1.FULL_DATE AND DD2.FULL_DATE THEN DD2.FULL_DATE ELSE NULL END  AS AUDIT_EFFECTIVE_END_DATE,
    COALESCE(SA.AUDIT_SCORE, NULL) AS AUDIT_SCORE,
    SPI.INVOICE_DATE,
    SPD.INVOICE_PAYMENT_AMOUNT_CAD AS PAYMENT_AMOUNT_CAD,
    CASE 
        WHEN SA.AUDIT_SCORE IS NOT NULL THEN SPD.INVOICE_PAYMENT_AMOUNT_CAD 
        ELSE 0
    END AS AUDIT_PAYMENT_AMOUNT_CAD,
    CASE WHEN SPI.INVOICE_DATE BETWEEN DD1.FULL_DATE AND DD2.FULL_DATE THEN TRUE ELSE FALSE END AS AUDIT_FLAGGED
FROM {{ ref ('sche_fact_Supplier_Payment_Detail') }} AS SPD
LEFT JOIN {{ ref ('sche_fact_Supplier_Payment') }} AS SP
    ON SPD.SUPPLIER_PAYMENT_SK = SP.SUPPLIER_PAYMENT_SK
LEFT JOIN {{ ref ('sche_fact_Purchase_Invoice') }} AS SPI
    ON SPD.SUPPLIER_PURCHASE_INVOICE_SK = SPI.SUPPLIER_PURCHASE_INVOICE_SK
LEFT JOIN {{ ref('sche_dim_Supplier') }} AS S
    ON SPI.SUPPLIER_SK = S.SUPPLIER_SK
LEFT JOIN {{ ref ('sche_fact_Supplier_Audit') }} AS SA
    ON S.SUPPLIER_SK = SA.SUPPLIER_SK
    AND CAST(SPI.INVOICE_DATE AS VARCHAR) BETWEEN SA.VALID_FROM_DATE_KEY AND SA.VALID_TO_DATE_KEY
LEFT JOIN {{ ref ('sche_dim_Date') }} AS DD1
    ON SA.VALID_FROM_DATE_KEY = DD1.DATE_KEY
LEFT JOIN {{ ref ('sche_dim_Date') }} AS DD2
    ON SA.VALID_TO_DATE_KEY = DD2.DATE_KEY